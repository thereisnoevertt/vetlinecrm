def FIG(caption_text):
    """Вставка изображения + подпись (или маркер, если файла нет)."""
    import re as _re, os as _os
    m = _re.match(r'Рисунок\s+([\d.]+)', caption_text)
    fname = FIG_MAP.get(m.group(1)) if m else None
    fpath = _os.path.join(DIAG_DIR, fname) if fname else None

    if fpath and _os.path.isfile(fpath):
        p_img = doc.add_paragraph()
        p_img.paragraph_format.first_line_indent = Cm(0)
        p_img.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_img.paragraph_format.space_before = Pt(8)
        p_img.paragraph_format.space_after = Pt(4)
        run = p_img.add_run()
        run.add_picture(fpath, width=Cm(15.5))
    else:
        box = doc.add_paragraph()
        box.paragraph_format.first_line_indent = Cm(0)
        box.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = box.add_run('[РИСУНОК — вставить здесь]')
        r.bold = True
        r.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)
        r.font.highlight_color = 7

    cap = doc.add_paragraph()
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(12)
    cap_r = cap.add_run(caption_text)
    cap_r.italic = True
    cap_r.font.size = Pt(12)

def TBL(headers, rows, caption=None):
    if caption:
        cap = doc.add_paragraph()
        cap.paragraph_format.first_line_indent = Cm(0)
        cr = cap.add_run(caption)
        cr.italic = True
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        para = hdr[i].paragraphs[0]
        para.paragraph_format.first_line_indent = Cm(0)
        run = para.add_run(h)
        run.bold = True
        run.font.size = Pt(12)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            para = cells[i].paragraphs[0]
            para.paragraph_format.first_line_indent = Cm(0)
            run = para.add_run(str(val))
            run.font.size = Pt(12)
    return t

