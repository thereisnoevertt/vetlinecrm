def make_marker_xml(text):
    return (
        '<w:p>'
          '<w:pPr>'
            '<w:spacing w:after="120"/>'
            '<w:jc w:val="center"/>'
          '</w:pPr>'
          '<w:r>'
            '<w:rPr>'
              '<w:b/>'
              '<w:color w:val="C00000"/>'
              '<w:sz w:val="20"/>'
              '<w:highlight w:val="yellow"/>'
            '</w:rPr>'
            '<w:t xml:space="preserve">' + text + '</w:t>'
          '</w:r>'
        '</w:p>'
    )

def insert_markers(xml):
    out, last, inserted = [], 0, 0
    for m in re.finditer(r'<w:p\b[^>]*>(?:(?!</w:p>).)*?<w:drawing\b.*?</w:p>',
                         xml, flags=re.DOTALL):
        out.append(xml[last:m.end()])
        out.append(make_marker_xml(MARKER_TEXT))
        last = m.end()
        inserted += 1
    out.append(xml[last:])
    return ''.join(out), inserted

