def replace_full_paragraph(xml, key, new_text):
    pat = re.compile(r'(<w:p\b[^>]*>)((?:(?!</w:p>).)*?' + re.escape(key) + r'.*?)(</w:p>)',
                     flags=re.DOTALL)
    def repl(m):
        head, body, tail = m.group(1), m.group(2), m.group(3)
        # сохраняем <w:pPr>, если есть
        pPr_match = re.match(r'(<w:pPr>.*?</w:pPr>)', body, flags=re.DOTALL)
        pPr = pPr_match.group(1) if pPr_match else ''
        new_run = ('<w:r><w:rPr><w:color w:val="000000"/></w:rPr>'
                   '<w:t xml:space="preserve">' + new_text + '</w:t></w:r>')
        return head + pPr + new_run + tail
    return pat.subn(repl, xml, count=1)

