def replace_in_text(xml, old, new):
    pattern = r'(<w:t(?:\s[^>]*)?>)([^<]*?)' + re.escape(old) + r'([^<]*?)(</w:t>)'
    def repl(m):
        return m.group(1) + m.group(2) + new + m.group(3) + m.group(4)
    return re.subn(pattern, repl, xml)

