-- V4__cleanup_pending_notifications.sql
-- Однократная очистка очереди уведомлений. Все застрявшие со старым
-- (зафиксированным при создании) текстом сообщения уведомления
-- помечаются ERROR, чтобы планировщик retryPending() не отправлял их
-- повторно после рестарта приложения. Менеджер при необходимости может
-- инициировать новую отправку вручную — текст будет сформирован уже
-- по актуальному статусу заявки (см. NotificationService.doSend).
UPDATE notifications
SET delivery_status = 'ERROR'
WHERE delivery_status = 'PENDING';
