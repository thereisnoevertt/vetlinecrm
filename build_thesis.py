# ─── Утилиты ─────────────────────────────────────────────────────
def remove_emoji(s: str) -> str:
    if not s:
        return s
    # Любые символы вне базового кириллического/латинского/пунктуационного
    # диапазона + явные эмодзи
    cleaned = []
    for ch in s:
        cp = ord(ch)
        if 0x1F300 <= cp <= 0x1FAFF: continue
        if 0x2600  <= cp <= 0x27BF:  continue
        if 0x1F000 <= cp <= 0x1F2FF: continue
        if cp in (0x2705, 0x274C, 0x2764, 0x2728): continue
        cleaned.append(ch)
    return ''.join(cleaned)

def P(text='', italic=False, bold=False, indent=None, align=None,
      size=None, after=None, before=None, no_indent=False,
      line_spacing=None):
    """Обычный абзац."""
    text = remove_emoji(text)
    p = doc.add_paragraph()
    pf = p.paragraph_format
    if no_indent:
        pf.first_line_indent = Cm(0)
    elif indent is not None:
        pf.first_line_indent = indent
    pf.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
    if after is not None:    pf.space_after = Pt(after)
    if before is not None:   pf.space_before = Pt(before)
    if line_spacing is not None: pf.line_spacing = line_spacing
    if text:
        r = p.add_run(text)
        r.italic = italic
        r.bold   = bold
        if size: r.font.size = Pt(size)
    return p

